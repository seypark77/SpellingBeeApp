"""
Generate offline mp3 pronunciations for all 450 words using Piper (open-source TTS).

Outputs:
  assets/audio/words/<id>.mp3
  src/utils/wordAudioMap.ts  (static require() map for Metro)
"""
import argparse
import json
import subprocess
import sys
import wave
from pathlib import Path

import imageio_ffmpeg
from piper import PiperVoice
from piper.config import SynthesisConfig

ROOT = Path(__file__).resolve().parent.parent
WORDS_JSON = ROOT / "src" / "data" / "words.json"
VOICE_DIR = ROOT / "scripts" / "piper_voices"
VOICE_NAME = "en_US-lessac-medium"
OUT_DIR = ROOT / "assets" / "audio" / "words"
MAP_TS = ROOT / "src" / "utils" / "wordAudioMap.ts"
FFMPEG = imageio_ffmpeg.get_ffmpeg_exe()

# Homograph phonetic override (#102 "lead" = metal /led/)
SPOKEN_OVERRIDES = {102: "led"}


def to_mp3(wav_path: Path, mp3_path: Path) -> None:
    subprocess.run(
        [
            FFMPEG,
            "-y",
            "-loglevel",
            "error",
            "-i",
            str(wav_path),
            "-ac",
            "1",
            "-ar",
            "22050",
            "-codec:a",
            "libmp3lame",
            "-b:a",
            "48k",
            str(mp3_path),
        ],
        check=True,
    )


def synth(voice: PiperVoice, text: str, wav_path: Path, length_scale: float = 1.05) -> None:
    cfg = SynthesisConfig(length_scale=length_scale)
    with wave.open(str(wav_path), "wb") as wf:
        voice.synthesize_wav(text, wf, syn_config=cfg)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--ids", type=int, nargs="*")
    args = ap.parse_args()

    model = VOICE_DIR / f"{VOICE_NAME}.onnx"
    if not model.exists():
        print(f"Voice model not found: {model}", file=sys.stderr)
        return 1

    voice = PiperVoice.load(str(model))
    words = json.loads(WORDS_JSON.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    tmp_wav = OUT_DIR / "_tmp.wav"

    for i, w in enumerate(words, 1):
        wid = w["id"]
        if args.ids and wid not in args.ids:
            continue
        out = OUT_DIR / f"{wid}.mp3"
        if out.exists() and not args.force:
            continue
        text = SPOKEN_OVERRIDES.get(wid, w["word"]).strip()
        synth(voice, text, tmp_wav, 1.05)
        to_mp3(tmp_wav, out)
        if i % 50 == 0:
            print(f"Generated {i}/{len(words)} words...", flush=True)

    if tmp_wav.exists():
        tmp_wav.unlink()

    # Build static require map (Metro needs literal require paths)
    lines = [
        "// AUTO-GENERATED by scripts/generate_word_audio.py - do not edit by hand.",
        "// Offline pronunciations generated with Piper (en_US-lessac-medium).",
        "",
        "export const WORD_AUDIO_ASSETS: Record<number, any> = {",
    ]
    for w in words:
        wid = w["id"]
        if (OUT_DIR / f"{wid}.mp3").exists():
            lines.append(f"  {wid}: require('../../assets/audio/words/{wid}.mp3'),")
    lines.append("};")
    lines.append("")
    MAP_TS.write_text("\n".join(lines), encoding="utf-8")
    print(f"Done! Map written to {MAP_TS}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
