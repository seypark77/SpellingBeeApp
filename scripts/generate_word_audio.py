"""
Generate offline mp3 pronunciations for all 450 words using Google US English TTS
and bundle them statically in assets/audio/words/<id>.mp3.
"""
import argparse
import concurrent.futures
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORDS_JSON = ROOT / "src" / "data" / "words.json"
OUT_DIR = ROOT / "assets" / "audio" / "words"
MAP_TS = ROOT / "src" / "utils" / "wordAudioMap.ts"

# Homograph phonetic override (#102 "lead" = metal /led/)
SPOKEN_OVERRIDES = {102: "led"}


def fetch_google_mp3(wid: int, text: str, out_path: Path) -> bool:
    q = urllib.parse.quote(text)
    url = f"https://translate.googleapis.com/translate_tts?ie=UTF-8&client=gtx&tl=en-US&ttsspeed=1&q={q}&ext=.mp3"
    req = urllib.request.Request(
        url,
        headers={
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
            "Referer": "https://translate.google.com/",
        },
    )
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                data = resp.read()
                if len(data) > 500:
                    out_path.write_bytes(data)
                    return True
        except Exception as e:
            if attempt == 2:
                print(f"Failed word #{wid} ({text}): {e}", file=sys.stderr)
            time.sleep(0.5 * (attempt + 1))
    return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", default=True)
    ap.add_argument("--ids", type=int, nargs="*")
    args = ap.parse_args()

    words = json.loads(WORDS_JSON.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    tasks = []
    for w in words:
        wid = w["id"]
        if args.ids and wid not in args.ids:
            continue
        out = OUT_DIR / f"{wid}.mp3"
        text = SPOKEN_OVERRIDES.get(wid, w["word"]).strip()
        tasks.append((wid, text, out))

    completed = 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        futures = {pool.submit(fetch_google_mp3, wid, text, out): wid for wid, text, out in tasks}
        for fut in concurrent.futures.as_completed(futures):
            completed += 1
            if completed % 50 == 0 or completed == len(tasks):
                print(f"Downloaded {completed}/{len(tasks)} Google US English MP3s...", flush=True)

    # Build static require map
    lines = [
        "// AUTO-GENERATED by scripts/generate_word_audio.py - do not edit by hand.",
        "// Bundled Google US English pronunciations.",
        "",
        "export const WORD_AUDIO_ASSETS: Record<number, any> = {",
    ]
    for w in words:
        wid = w["id"]
        if (OUT_DIR / f"{wid}.mp3").exists():
            lines.append(f"  {wid}: require('../../assets/audio/words/{wid}.mp3'),")
    lines.append("};")
    lines.append("")
    MAP_TS.write_text("\n".join(lines), encoding="utf-8")
    print(f"Done! Map written to {MAP_TS}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
