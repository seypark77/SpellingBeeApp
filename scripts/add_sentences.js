function makeBlankedSentence(sentence, word, altSpellings) {
  const forms = [word, ...(altSpellings || [])].filter(Boolean);
  let result = sentence;
  for (const form of forms) {
    const escaped = form.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`\\b${escaped}\\b`, 'gi');
    result = result.replace(regex, '________');
  }
  if (!result.includes('________')) {
    // Fallback case-insensitive substring replacement
    const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(escaped, 'gi');
    result = result.replace(regex, '________');
  }
  return result;
}

const enriched = words.map((entry) => {
  const sentence = sentencesById[entry.id];
  if (!sentence) {
    throw new Error(`Missing sentence for word ID ${entry.id} (${entry.word})`);
  }
  const blankedSentence = makeBlankedSentence(sentence, entry.word, entry.altSpellings);
  if (!blankedSentence.includes('________')) {
    console.warn(`Warning: blankedSentence for ID ${entry.id} (${entry.word}) did not blank: ${sentence}`);
  }
  return {
    ...entry,
    exampleSentence: sentence,
    blankedSentence,
    mwUrl: `https://www.merriam-webster.com/dictionary/${encodeURIComponent(entry.word)}`
  };
});

